#!/usr/bin/env bash
# Regenerate the tier-2 skill-archive index from SKILL.md frontmatter.
# Pure bash+awk: no python, no YAML dependency.
#
#   scripts/skills-index.sh [archive-dir=skill-archive] > INDEX.md (in-place by default)
#
# Handles bare, double-quoted, and folded (>- / > / |- / |) description
# scalars; fails loudly (exit 1) on malformed frontmatter so a broken
# skill can never silently vanish from the discovery surface.
# LC_ALL is forced to a UTF-8 locale so gawk truncates by character,
# not byte — em-dashes in descriptions must not mangle.
set -euo pipefail
export LC_ALL=C.UTF-8

root="${1:-skill-archive}"
index="$root/INDEX.md"

[ -d "$root" ] || {
  echo "skills-index: no such directory: $root" >&2
  exit 1
}

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

while IFS= read -r f; do
  rel="${f#"$root"/}"
  rel="${rel%/SKILL.md}"
  REL="$rel" awk -v rel="$rel" '
    function done_fold() { if (folding) { desc = folded; folding = 0 } }
    /^---$/ {
      if (!in_fm) { in_fm = 1; next }
      closed = 1; done_fold(); exit
    }
    !in_fm { next }
    folding && /^[[:space:]]/ {
      s = $0; sub(/^[[:space:]]+/, "", s)
      folded = folded (folded == "" ? "" : " ") s
      next
    }
    folding { done_fold() }
    /^name:/ {
      s = $0; sub(/^name:[[:space:]]*/, "", s)
      gsub(/^"|"$/, "", s); name = s; next
    }
    /^description:/ {
      s = $0; sub(/^description:[[:space:]]*/, "", s)
      if (s == ">" || s == ">-" || s == ">+" || s == "|" || s == "|-" || s == "|+") {
        folding = 1; folded = ""; next
      }
      gsub(/^"|"$/, "", s); desc = s; next
    }
    END {
      if (!closed)               { print "frontmatter not closed"          > "/dev/stderr"; exit 1 }
      if (name == "")            { print "frontmatter missing name:"       > "/dev/stderr"; exit 1 }
      if (desc == "")            { print "frontmatter missing description:"> "/dev/stderr"; exit 1 }
      # first sentence, capped at 140 chars (character-based in UTF-8 locale)
      i = index(desc, ". ")
      if (i > 0) desc = substr(desc, 1, i - 1)
      if (length(desc) > 140) desc = substr(desc, 1, 137) "..."
      gsub(/\|/, "\\|", desc)
      printf "| `%s` | `%s` | %s |\n", name, rel, desc
    }
  ' "$f" >>"$tmp" || {
    echo "skills-index: malformed frontmatter in $f" >&2
    exit 1
  }
done < <(find "$root" -name SKILL.md -not -path '*/.*' | sort)

count="$(wc -l <"$tmp")"
{
  echo "# Skill Archive index"
  echo ""
  echo "GENERATED by scripts/skills-index.sh — do not edit by hand;"
  echo 'regenerate with `just skills-index` and commit with any archive change.'
  echo "$count skills. The archive is tier 2: search-only, loads into no prompt."
  echo ""
  echo "| Skill | Path | Description |"
  echo "|---|---|---|"
  cat "$tmp"
} >"$index"

echo "wrote $index ($count skills)"
